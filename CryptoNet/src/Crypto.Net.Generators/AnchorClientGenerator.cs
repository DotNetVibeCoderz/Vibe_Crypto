using System;
using System.Collections.Generic;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using static Crypto.Net.Generators.MiniJson;

namespace Crypto.Net.Generators;

/// <summary>
/// Generates a Solana client from an Anchor IDL (the 0.30+ format with <c>address</c>/<c>discriminator</c>, or the older
/// format with <c>isMut</c>/<c>isSigner</c>). Instructions become <c>SolanaInstruction</c> builders with Borsh-encoded
/// arguments, account types become records with discriminator-checked decoders and <c>Fetch…Async</c> helpers, and
/// errors become a code → message table.
/// </summary>
public static class AnchorClientGenerator
{
    private sealed class Ctx
    {
        public Dictionary<string, Dictionary<string, object?>> Types = new(StringComparer.Ordinal);
        public HashSet<string> Emitted = new(StringComparer.Ordinal);
        public int Temp;
    }

    public static string Generate(string json, string ns, string className)
    {
        var idl = Obj(MiniJson.Parse(json));
        var meta = Get(idl, "metadata") as Dictionary<string, object?>;
        string programName = Str(idl, "name") ?? (meta is null ? null : Str(meta, "name")) ?? className;
        string? address = Str(idl, "address") ?? (meta is null ? null : Str(meta, "address"));
        bool newFormat = Get(idl, "address") is string || Arr(idl, "instructions").Select(Obj).Any(i => Get(i, "discriminator") is not null);
        string cls = Names.Pascal(className, "Program");
        if (!cls.EndsWith("Program", StringComparison.Ordinal)) cls += "Program"; // account records may share the base name
        var ctx = new Ctx();

        foreach (var t in Arr(idl, "types").Select(Obj)) ctx.Types[Str(t, "name") ?? ""] = t;
        // Old IDLs define account layouts inline under "accounts".
        foreach (var a in Arr(idl, "accounts").Select(Obj))
            if (Get(a, "type") is Dictionary<string, object?> && !ctx.Types.ContainsKey(Str(a, "name") ?? "")) ctx.Types[Str(a, "name") ?? ""] = a;

        var code = new Code();
        code.Line("// <auto-generated>Generated by Crypto.Net.Generators from an Anchor IDL. Do not edit.</auto-generated>");
        code.Line("#nullable enable");
        code.Line("#pragma warning disable CS1591");
        code.Line("using System.Numerics;");
        code.Line("using Crypto.Net.Solana;");
        code.Line();
        if (!string.IsNullOrEmpty(ns)) code.Line($"namespace {ns};").Line();
        code.Line($"/// <summary>Client for the <c>{programName}</c> Anchor program.</summary>");
        code.Line($"public static partial class {cls}");
        code.Line("{");
        if (address is not null) code.Line($"public const string ProgramId = {Names.Literal(address)};");
        else code.Line("public const string ProgramId = \"\"; // the IDL has no address: pass programId explicitly");

        // Instructions
        foreach (var ix in Arr(idl, "instructions").Select(Obj))
        {
            string name = Str(ix, "name") ?? "instruction";
            byte[] disc = Get(ix, "discriminator") is List<object?> d ? d.Select(x => Convert.ToByte(x)).ToArray() : Sha8("global:" + Names.Snake(name));
            var accounts = new List<(string Param, bool Writable, bool Signer, bool Optional, string? Fixed)>();
            Flatten(Arr(ix, "accounts"), "", accounts);
            var args = Arr(ix, "args").Select(Obj).Select((a, i) => (Name: Names.Camel(Str(a, "name"), "arg" + i), Type: Get(a, "type"))).ToList();

            var used = new HashSet<string>(StringComparer.Ordinal) { "programId", "w" };
            var parameters = new List<string>();
            var accountNames = new List<string>();
            foreach (var acc in accounts.Where(a => a.Fixed is null && !a.Optional))
            {
                string p = Unique(acc.Param, used);
                accountNames.Add(p);
                parameters.Add($"string {p}");
            }
            var argNames = new List<string>();
            foreach (var a in args)
            {
                string p = Unique(a.Name, used);
                argNames.Add(p);
                parameters.Add($"{CsType(a.Type, ctx)} {p}");
            }
            var optionalNames = new List<string>();
            foreach (var acc in accounts.Where(a => a.Fixed is null && a.Optional))
            {
                string p = Unique(acc.Param, used);
                optionalNames.Add(p);
                parameters.Add($"string? {p} = null");
            }
            parameters.Add("string? programId = null");

            code.Line();
            code.Line($"/// <summary><c>{name}</c> instruction.</summary>");
            code.Line($"public static SolanaInstruction {Names.Pascal(name, "Instruction")}({string.Join(", ", parameters)})");
            code.Line("{");
            code.Line("string pid = programId ?? ProgramId;");
            code.Line("var w = new BorshWriter();");
            code.Line($"w.Bytes(new byte[] {{ {string.Join(", ", disc.Select(b => "0x" + b.ToString("x2")))} }});");
            for (int i = 0; i < args.Count; i++) EmitWrite(code, args[i].Type, argNames[i], ctx);
            code.Line("var accounts = new System.Collections.Generic.List<AccountMeta>");
            code.Line("{");
            int required = 0, optional = 0;
            foreach (var acc in accounts)
            {
                string key = acc.Fixed is not null ? Names.Literal(acc.Fixed) : acc.Optional ? $"{optionalNames[optional++]} ?? pid" : accountNames[required++];
                // Anchor passes the program id for an omitted optional account; it is never writable or a signer then.
                string writable = acc.Optional && acc.Fixed is null ? $"{acc.Writable.ToString().ToLowerInvariant()} && {optionalNames[optional - 1]} is not null" : acc.Writable.ToString().ToLowerInvariant();
                string signer = acc.Optional && acc.Fixed is null ? $"{acc.Signer.ToString().ToLowerInvariant()} && {optionalNames[optional - 1]} is not null" : acc.Signer.ToString().ToLowerInvariant();
                code.Line($"new AccountMeta({key}, {signer}, {writable}),");
            }
            code.Line("};");
            code.Line("return new SolanaInstruction(pid, accounts, w.ToArray());");
            code.Line("}");
        }

        // Accounts
        foreach (var acc in Arr(idl, "accounts").Select(Obj))
        {
            string name = Str(acc, "name") ?? "";
            if (!ctx.Types.ContainsKey(name)) continue;
            byte[] disc = Get(acc, "discriminator") is List<object?> d ? d.Select(x => Convert.ToByte(x)).ToArray() : Sha8("account:" + name);
            string type = Names.Pascal(name, "Account");
            code.Line();
            code.Line($"public static readonly byte[] {type}Discriminator = new byte[] {{ {string.Join(", ", disc.Select(b => "0x" + b.ToString("x2")))} }};");
            code.Line();
            code.Line($"/// <summary>Decodes a <c>{name}</c> account (checks the discriminator).</summary>");
            code.Line($"public static {type} Decode{type}(System.ReadOnlySpan<byte> data)");
            code.Line("{");
            code.Line($"var r = new BorshReader(Anchor.AccountPayload(data, {type}Discriminator));");
            code.Line($"return {type}.Read(ref r);");
            code.Line("}");
            code.Line();
            code.Line($"public static async System.Threading.Tasks.ValueTask<{type}?> Fetch{type}Async(SolanaRpcClient rpc, string address, System.Threading.CancellationToken ct = default)");
            code.Line("{");
            code.Line("byte[]? data = await rpc.GetAccountDataAsync(address, ct).ConfigureAwait(false);");
            code.Line($"return data is null ? null : Decode{type}(data);");
            code.Line("}");
        }

        // Errors
        var errors = Arr(idl, "errors").Select(Obj).ToList();
        if (errors.Count > 0)
        {
            code.Line();
            code.Line("/// <summary>Program error message for a custom error code, or null.</summary>");
            code.Line("public static string? ErrorMessage(int code) => code switch");
            code.Line("{");
            foreach (var e in errors)
                code.Line($"{Convert.ToInt64(Get(e, "code"))} => {Names.Literal((Str(e, "name") ?? "") + (Str(e, "msg") is { } m ? ": " + m : ""))},");
            code.Line("_ => null,");
            code.Line("};");
        }

        // Types (emit everything defined, so account and argument types exist)
        foreach (var t in ctx.Types.Keys.ToList()) EmitType(code, t, ctx);

        code.Line("}");
        return code.ToString();
    }

    private static string Unique(string name, HashSet<string> used)
    {
        while (!used.Add(name)) name += "_";
        return name;
    }

    private static void Flatten(List<object?> accounts, string prefix, List<(string, bool, bool, bool, string?)> into)
    {
        foreach (var a in accounts.Select(Obj))
        {
            string name = Str(a, "name") ?? "account";
            if (Get(a, "accounts") is List<object?> nested)
            {
                Flatten(nested, prefix + Names.Pascal(name) , into);
                continue;
            }
            bool writable = Bool(a, "writable") || Bool(a, "isMut");
            bool signer = Bool(a, "signer") || Bool(a, "isSigner");
            bool optional = Bool(a, "optional") || Bool(a, "isOptional");
            string param = prefix.Length == 0 ? Names.Camel(name, "account") : Names.Camel(prefix + Names.Pascal(name), "account");
            into.Add((param, writable, signer, optional, Str(a, "address")));
        }
    }

    private static byte[] Sha8(string preimage)
    {
        using var sha = SHA256.Create();
        return sha.ComputeHash(Encoding.UTF8.GetBytes(preimage)).Take(8).ToArray();
    }

    private static string DefinedName(object? defined) => defined switch
    {
        string s => s,
        Dictionary<string, object?> d => Str(d, "name") ?? throw new FormatException("defined type without name"),
        _ => throw new FormatException("Invalid defined type"),
    };

    private static string CsType(object? type, Ctx ctx)
    {
        switch (type)
        {
            case string s:
                return s switch
                {
                    "bool" => "bool",
                    "u8" => "byte",
                    "i8" => "sbyte",
                    "u16" => "ushort",
                    "i16" => "short",
                    "u32" => "uint",
                    "i32" => "int",
                    "u64" => "ulong",
                    "i64" => "long",
                    "u128" or "i128" or "u256" or "i256" => "BigInteger",
                    "f32" => "float",
                    "f64" => "double",
                    "string" => "string",
                    "bytes" => "byte[]",
                    "pubkey" or "publicKey" => "string",
                    _ => throw new FormatException($"Unsupported IDL type '{s}'"),
                };
            case Dictionary<string, object?> d:
                if (Get(d, "vec") is { } v) return IsU8(v) ? "byte[]" : CsType(v, ctx) + "[]";
                if (Get(d, "array") is List<object?> arr) return IsU8(arr[0]) ? "byte[]" : CsType(arr[0], ctx) + "[]";
                if (Get(d, "option") is { } o) return CsType(o, ctx) + "?";
                if (Get(d, "coption") is { } co) return CsType(co, ctx) + "?";
                if (Get(d, "defined") is { } def) return Names.Pascal(DefinedName(def), "Type");
                break;
        }
        throw new FormatException("Unsupported IDL type");
    }

    private static bool IsU8(object? t) => t is string s && s == "u8";

    private static void EmitWrite(Code code, object? type, string expr, Ctx ctx)
    {
        switch (type)
        {
            case string s:
                code.Line(s switch
                {
                    "bool" => $"w.Bool({expr});",
                    "u8" => $"w.U8({expr});",
                    "i8" => $"w.I8({expr});",
                    "u16" => $"w.U16({expr});",
                    "i16" => $"w.I16({expr});",
                    "u32" => $"w.U32({expr});",
                    "i32" => $"w.I32({expr});",
                    "u64" => $"w.U64({expr});",
                    "i64" => $"w.I64({expr});",
                    "u128" => $"w.U128({expr});",
                    "i128" => $"w.I128({expr});",
                    "u256" => $"w.U256({expr});",
                    "f32" => $"w.F32({expr});",
                    "f64" => $"w.F64({expr});",
                    "string" => $"w.String({expr});",
                    "bytes" => $"w.VecU8({expr});",
                    "pubkey" or "publicKey" => $"w.PublicKey({expr});",
                    _ => throw new FormatException($"Unsupported IDL type '{s}'"),
                });
                return;
            case Dictionary<string, object?> d:
                if (Get(d, "vec") is { } v)
                {
                    if (IsU8(v)) { code.Line($"w.VecU8({expr});"); return; }
                    string e = "e" + ctx.Temp++;
                    code.Line($"w.U32(checked((uint){expr}.Length));");
                    code.Line($"foreach (var {e} in {expr})");
                    code.Line("{");
                    EmitWrite(code, v, e, ctx);
                    code.Line("}");
                    return;
                }
                if (Get(d, "array") is List<object?> arr)
                {
                    long len = Convert.ToInt64(arr[1]);
                    code.Line($"if ({expr}.Length != {len}) throw new System.ArgumentException(\"Expected {len} items\");");
                    if (IsU8(arr[0])) { code.Line($"w.Bytes({expr});"); return; }
                    string e = "e" + ctx.Temp++;
                    code.Line($"foreach (var {e} in {expr})");
                    code.Line("{");
                    EmitWrite(code, arr[0], e, ctx);
                    code.Line("}");
                    return;
                }
                if ((Get(d, "option") ?? Get(d, "coption")) is { } o)
                {
                    bool coption = Get(d, "coption") is not null;
                    string e = "o" + ctx.Temp++;
                    code.Line($"if ({expr} is {{ }} {e})");
                    code.Line("{");
                    code.Line(coption ? "w.U32(1);" : "w.U8(1);");
                    EmitWrite(code, o, e, ctx);
                    code.Line("}");
                    code.Line("else");
                    code.Line("{");
                    code.Line(coption ? "w.U32(0);" : "w.U8(0);");
                    code.Line("}");
                    return;
                }
                if (Get(d, "defined") is { } def)
                {
                    code.Line($"{expr}.Write(w);");
                    return;
                }
                break;
        }
        throw new FormatException("Unsupported IDL type");
    }

    // Emits statements that read a value of 'type' into a new local, and returns the local's name.
    private static string EmitRead(Code code, object? type, Ctx ctx)
    {
        string v = "v" + ctx.Temp++;
        switch (type)
        {
            case string s:
                string read = s switch
                {
                    "bool" => "r.Bool()",
                    "u8" => "r.U8()",
                    "i8" => "r.I8()",
                    "u16" => "r.U16()",
                    "i16" => "r.I16()",
                    "u32" => "r.U32()",
                    "i32" => "r.I32()",
                    "u64" => "r.U64()",
                    "i64" => "r.I64()",
                    "u128" => "r.U128()",
                    "i128" => "r.I128()",
                    "u256" => "r.U256()",
                    "f32" => "r.F32()",
                    "f64" => "r.F64()",
                    "string" => "r.String()",
                    "bytes" => "r.VecU8()",
                    "pubkey" or "publicKey" => "r.PublicKey()",
                    _ => throw new FormatException($"Unsupported IDL type '{s}'"),
                };
                code.Line($"var {v} = {read};");
                return v;
            case Dictionary<string, object?> d:
                if (Get(d, "vec") is { } vec)
                {
                    if (IsU8(vec)) { code.Line($"var {v} = r.VecU8();"); return v; }
                    string n = "n" + ctx.Temp++, i = "i" + ctx.Temp++;
                    code.Line($"int {n} = r.VecLength();");
                    code.Line($"var {v} = new {CsType(vec, ctx)}[{n}];");
                    code.Line($"for (int {i} = 0; {i} < {n}; {i}++)");
                    code.Line("{");
                    string item = EmitRead(code, vec, ctx);
                    code.Line($"{v}[{i}] = {item};");
                    code.Line("}");
                    return v;
                }
                if (Get(d, "array") is List<object?> arr)
                {
                    long len = Convert.ToInt64(arr[1]);
                    if (IsU8(arr[0])) { code.Line($"var {v} = r.Bytes({len}).ToArray();"); return v; }
                    string i = "i" + ctx.Temp++;
                    code.Line($"var {v} = new {CsType(arr[0], ctx)}[{len}];");
                    code.Line($"for (int {i} = 0; {i} < {len}; {i}++)");
                    code.Line("{");
                    string item = EmitRead(code, arr[0], ctx);
                    code.Line($"{v}[{i}] = {item};");
                    code.Line("}");
                    return v;
                }
                if ((Get(d, "option") ?? Get(d, "coption")) is { } o)
                {
                    bool coption = Get(d, "coption") is not null;
                    code.Line($"{CsType(o, ctx)}? {v} = default;");
                    code.Line(coption ? "if (r.U32() != 0)" : "if (r.Option())");
                    code.Line("{");
                    string item = EmitRead(code, o, ctx);
                    code.Line($"{v} = {item};");
                    code.Line("}");
                    return v;
                }
                if (Get(d, "defined") is { } def)
                {
                    string dn = DefinedName(def);
                    string tn = Names.Pascal(dn, "Type");
                    code.Line(IsUnitEnum(dn, ctx) ? $"var {v} = Read{tn}(ref r);" : $"var {v} = {tn}.Read(ref r);");
                    return v;
                }
                break;
        }
        throw new FormatException("Unsupported IDL type");
    }

    private static bool IsUnitEnum(string name, Ctx ctx) =>
        ctx.Types.TryGetValue(name, out var def) && Get(def, "type") is Dictionary<string, object?> t && Str(t, "kind") == "enum"
        && Arr(t, "variants").Select(Obj).All(v => Arr(v, "fields").Count == 0);

    private static void EmitType(Code code, string name, Ctx ctx)
    {
        if (!ctx.Emitted.Add(name)) return;
        var def = ctx.Types[name];
        var type = Obj(Get(def, "type"));
        string kind = Str(type, "kind") ?? "struct";
        string cs = Names.Pascal(name, "Type");
        code.Line();
        if (kind == "struct")
        {
            var fields = Arr(type, "fields").Select((f, i) => f is Dictionary<string, object?> fd
                ? (Name: Names.Pascal(Str(fd, "name"), "Item" + i), Type: Get(fd, "type"))
                : (Name: "Item" + i, Type: f)).ToList();
            code.Line($"public sealed record {cs}({string.Join(", ", fields.Select(f => $"{CsType(f.Type, ctx)} {f.Name}"))})");
            code.Line("{");
            code.Line("public void Write(BorshWriter w)");
            code.Line("{");
            foreach (var f in fields) EmitWrite(code, f.Type, f.Name, ctx);
            code.Line("}");
            code.Line();
            code.Line($"public static {cs} Read(ref BorshReader r)");
            code.Line("{");
            var locals = fields.Select(f => EmitRead(code, f.Type, ctx)).ToList();
            code.Line($"return new {cs}({string.Join(", ", locals)});");
            code.Line("}");
            code.Line("}");
            return;
        }
        if (kind == "enum")
        {
            var variants = Arr(type, "variants").Select(Obj).ToList();
            if (variants.All(v => Arr(v, "fields").Count == 0))
            {
                // Unit-only enum: a C# enum plus Borsh helpers.
                code.Line($"public enum {cs} : byte");
                code.Line("{");
                foreach (var v in variants) code.Line($"{Names.Pascal(Str(v, "name"), "Variant")},");
                code.Line("}");
                code.Line();
                code.Line($"private static void Write(this {cs} value, BorshWriter w) => w.U8((byte)value);");
                code.Line();
                code.Line($"private static {cs} Read{cs}(ref BorshReader r)");
                code.Line("{");
                code.Line("byte tag = r.U8();");
                code.Line($"if (tag >= {variants.Count}) throw new System.FormatException(\"Invalid {cs} variant\");");
                code.Line($"return ({cs})tag;");
                code.Line("}");
                return;
            }
            code.Line($"public abstract record {cs}");
            code.Line("{");
            code.Line("public abstract void Write(BorshWriter w);");
            code.Line();
            for (int vi = 0; vi < variants.Count; vi++)
            {
                var v = variants[vi];
                string vn = Names.Pascal(Str(v, "name"), "Variant" + vi);
                var fields = Arr(v, "fields").Select((f, i) => f is Dictionary<string, object?> fd
                    ? (Name: Names.Pascal(Str(fd, "name"), "Item" + i), Type: Get(fd, "type"))
                    : (Name: "Item" + i, Type: f)).ToList();
                code.Line($"public sealed record {vn}({string.Join(", ", fields.Select(f => $"{CsType(f.Type, ctx)} {f.Name}"))}) : {cs}");
                code.Line("{");
                code.Line("public override void Write(BorshWriter w)");
                code.Line("{");
                code.Line($"w.U8({vi});");
                foreach (var f in fields) EmitWrite(code, f.Type, f.Name, ctx);
                code.Line("}");
                code.Line("}");
                code.Line();
            }
            code.Line($"public static {cs} Read(ref BorshReader r)");
            code.Line("{");
            code.Line("switch (r.U8())");
            code.Line("{");
            for (int vi = 0; vi < variants.Count; vi++)
            {
                var v = variants[vi];
                string vn = Names.Pascal(Str(v, "name"), "Variant" + vi);
                var fields = Arr(v, "fields").Select(f => f is Dictionary<string, object?> fd ? Get(fd, "type") : f).ToList();
                code.Line($"case {vi}:");
                code.Line("{");
                var locals = fields.Select(f => EmitRead(code, f, ctx)).ToList();
                code.Line($"return new {vn}({string.Join(", ", locals)});");
                code.Line("}");
            }
            code.Line("default: throw new System.FormatException(\"Invalid enum variant\");");
            code.Line("}");
            code.Line("}");
            code.Line("}");
            return;
        }
        throw new FormatException($"Unsupported IDL type kind '{kind}' for {name}");
    }
}
