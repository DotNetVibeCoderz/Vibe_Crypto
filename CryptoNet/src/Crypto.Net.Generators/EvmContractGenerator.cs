using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using static Crypto.Net.Generators.MiniJson;

namespace Crypto.Net.Generators;

/// <summary>
/// Generates a typed <c>EvmContract</c> client from Solidity ABI JSON: an ABI array, or a Hardhat/Foundry artifact
/// with an <c>abi</c> property. Views become <c>…Async</c> calls returning typed values, state-changing functions become
/// signer-based <c>…Async</c> sends plus static <c>Encode…</c> calldata builders, structs become records and events
/// become <c>EvmEvent</c> definitions with typed <c>…Event</c> records.
/// </summary>
public static class EvmContractGenerator
{
    private sealed class Param
    {
        public string Name = "";
        public string Type = "";            // e.g. uint256, tuple[2][]
        public string? InternalType;
        public List<Param> Components = new();
        public bool Indexed;
    }

    private sealed class Struct
    {
        public string Name = "";
        public List<Param> Fields = new();
    }

    public static string Generate(string json, string ns, string className)
    {
        object? root = MiniJson.Parse(json);
        List<object?> abi = root is Dictionary<string, object?> artifact ? Arr(artifact, "abi") : Arr(root);
        var structs = new Dictionary<string, Struct>(StringComparer.Ordinal);
        var code = new Code();
        string cls = Names.Pascal(className, "Contract");
        _contractName = cls;

        code.Line("// <auto-generated>Generated by Crypto.Net.Generators from Solidity ABI. Do not edit.</auto-generated>");
        code.Line("#nullable enable");
        code.Line("#pragma warning disable CS1591");
        code.Line("using System.Numerics;");
        code.Line("using Crypto.Net.Core;");
        code.Line("using Crypto.Net.Evm;");
        code.Line();
        if (!string.IsNullOrEmpty(ns)) code.Line($"namespace {ns};").Line();
        code.Line($"/// <summary>Typed client for the {Names.Literal(className).Trim('"')} contract.</summary>");
        code.Line($"public partial class {cls} : EvmContract");
        code.Line("{");
        code.Line($"public {cls}(EvmRpcClient rpc, string address) : base(rpc, address)");
        code.Line("{");
        code.Line("}");

        var functions = abi.Select(Obj).Where(e => Str(e, "type") is null or "function").ToList();
        var usedSignatures = new HashSet<string>(StringComparer.Ordinal);
        foreach (var fn in functions)
        {
            string name = Str(fn, "name") ?? "";
            if (name.Length == 0) continue;
            var inputs = Params(Arr(fn, "inputs"));
            var outputs = Params(Arr(fn, "outputs"));
            string mutability = Str(fn, "stateMutability") ?? (Bool(fn, "constant") ? "view" : Bool(fn, "payable") ? "payable" : "nonpayable");
            string signature = $"{name}({string.Join(",", inputs.Select(Canonical))})";
            string method = Names.Pascal(name, "Function");
            var args = Arguments(inputs, structs, method);
            string csKey = method + "(" + string.Join(",", args.Select(a => a.Type)) + ")";
            if (!usedSignatures.Add(csKey))
            {
                int n = 2;
                while (!usedSignatures.Add(method + n + "(" + string.Join(",", args.Select(a => a.Type)) + ")")) n++;
                method += n;
            }
            string argList = string.Join(", ", args.Select(a => $"{a.Type} {a.Name}"));
            string argValues = args.Count == 0 ? "System.Array.Empty<object?>()" : "new object?[] { " + string.Join(", ", args.Select(a => a.ToAbi)) + " }";
            code.Line();
            code.Line($"/// <summary><c>{signature}</c> ({mutability}).</summary>");

            if (mutability is "view" or "pure")
            {
                string outTypes = string.Join(",", outputs.Select(Canonical));
                string returnType;
                string body;
                if (outputs.Count == 0)
                {
                    returnType = "System.Threading.Tasks.ValueTask";
                    body = $"await CallAsync({Names.Literal(signature)}, \"\", {argValues}, block, ct).ConfigureAwait(false);";
                }
                else if (outputs.Count == 1)
                {
                    returnType = $"System.Threading.Tasks.ValueTask<{CsType(outputs[0], structs, method + "Result")}>";
                    body = $"return {FromAbi(outputs[0], "r[0]", structs, method + "Result", 0)};";
                }
                else
                {
                    string record = method + "Output";
                    var fields = outputs.Select((o, i) => (Prop: Names.Pascal(o.Name, "Item" + (i + 1)), Type: CsType(o, structs, method + "Output" + i), Param: o)).ToList();
                    code.Line($"public sealed record {record}({string.Join(", ", fields.Select(f => $"{f.Type} {f.Prop}"))});");
                    returnType = $"System.Threading.Tasks.ValueTask<{record}>";
                    body = $"return new {record}({string.Join(", ", fields.Select((f, i) => FromAbi(f.Param, $"r[{i}]", structs, method + "Output" + i, 0)))});";
                }
                string sep = argList.Length > 0 ? ", " : "";
                code.Line($"public async {returnType} {method}Async({argList}{sep}string block = \"latest\", System.Threading.CancellationToken ct = default)");
                code.Line("{");
                if (outputs.Count == 0) code.Line(body);
                else
                {
                    code.Line($"var r = await CallAsync({Names.Literal(signature)}, {Names.Literal(outTypes)}, {argValues}, block, ct).ConfigureAwait(false);");
                    code.Line(body);
                }
                code.Line("}");
            }
            else
            {
                string sep = argList.Length > 0 ? ", " : "";
                string valueParam = mutability == "payable" ? ", BigInteger valueWei" : "";
                string valueArg = mutability == "payable" ? "valueWei" : "BigInteger.Zero";
                code.Line($"public System.Threading.Tasks.ValueTask<TxHash> {method}Async(ISigner signer{sep}{argList}{valueParam}, System.Threading.CancellationToken ct = default) =>");
                code.Line($"    SendAsync(signer, {Names.Literal(signature)}, {argValues}, {valueArg}, ct);");
                code.Line();
                code.Line($"/// <summary>Calldata for <c>{signature}</c>.</summary>");
                code.Line($"public static byte[] Encode{method}({argList}) =>");
                code.Line($"    EvmAbi.EncodeFunctionCall({Names.Literal(signature)}, {argValues});");
            }
        }

        // Events
        var events = abi.Select(Obj).Where(e => Str(e, "type") == "event").ToList();
        if (events.Count > 0)
        {
            code.Line();
            code.Line("/// <summary>Event definitions, usable with <c>EvmLogIndexer</c> and <c>SubscribeEvmLogsAsync</c>.</summary>");
            code.Line("public static class Events");
            code.Line("{");
            var seen = new HashSet<string>(StringComparer.Ordinal);
            foreach (var ev in events)
            {
                string name = Str(ev, "name") ?? "";
                string field = Names.Pascal(name, "Event");
                while (!seen.Add(field)) field += "_";
                var inputs = Params(Arr(ev, "inputs"));
                string human = $"{name}({string.Join(", ", inputs.Select((p, i) => $"{Canonical(p)}{(p.Indexed ? " indexed" : "")} {Names.Clean(p.Name, "arg" + i)}"))}){(Bool(ev, "anonymous") ? " anonymous" : "")}";
                code.Line($"public static readonly EvmEvent {field} = EvmEvent.Parse({Names.Literal(human)});");
            }
            code.Line("}");

            seen.Clear();
            foreach (var ev in events)
            {
                string name = Str(ev, "name") ?? "";
                string field = Names.Pascal(name, "Event");
                while (!seen.Add(field)) field += "_";
                var inputs = Params(Arr(ev, "inputs"));
                var props = inputs.Select((p, i) =>
                {
                    bool hashed = p.Indexed && IsDynamicOrComposite(p);
                    return (Prop: Names.Pascal(p.Name, "Arg" + i), Key: Names.Clean(p.Name, "arg" + i), Param: p, Hashed: hashed,
                        Type: hashed ? "byte[]" : CsType(p, structs, field + "Arg" + i));
                }).ToList();
                code.Line();
                code.Line($"/// <summary>Decoded <c>{name}</c> event (indexed dynamic values are their keccak-256 hash).</summary>");
                string ctorArgs = string.Join(", ", props.Select(p => $"{p.Type} {p.Prop}"));
                code.Line($"public sealed record {field}Event({ctorArgs}{(props.Count > 0 ? ", " : "")}EvmLog Log)");
                code.Line("{");
                code.Line($"public static bool TryDecode(EvmLog log, out {field}Event? decoded)");
                code.Line("{");
                code.Line("decoded = null;");
                code.Line($"if (!Events.{field}.TryDecode(log, out var e)) return false;");
                string values = string.Join(", ", props.Select(p => p.Hashed ? $"(byte[])e![{Names.Literal(p.Key)}]!" : FromAbi(p.Param, $"e![{Names.Literal(p.Key)}]", structs, field + "Arg", 0)));
                code.Line($"decoded = new {field}Event({values}{(props.Count > 0 ? ", " : "")}log);");
                code.Line("return true;");
                code.Line("}");
                code.Line("}");
            }
        }

        // Structs (emitted last, after every use registered them)
        foreach (var s in structs.Values)
        {
            code.Line();
            var fields = s.Fields.Select((f, i) => (Prop: Names.Pascal(f.Name, "Item" + (i + 1)), Type: CsType(f, structs, s.Name + "Item" + i), Param: f)).ToList();
            code.Line($"public sealed record {s.Name}({string.Join(", ", fields.Select(f => $"{f.Type} {f.Prop}"))})");
            code.Line("{");
            code.Line($"internal object?[] ToAbi() => new object?[] {{ {string.Join(", ", fields.Select(f => ToAbi(f.Param, f.Prop, structs, 0)))} }};");
            code.Line();
            code.Line($"internal static {s.Name} FromAbi(object? value)");
            code.Line("{");
            code.Line("var f = Fields(value);");
            code.Line($"return new {s.Name}({string.Join(", ", fields.Select((f, i) => FromAbi(f.Param, $"f[{i}]", structs, s.Name + "Item" + i, 0)))});");
            code.Line("}");
            code.Line("}");
        }

        code.Line("}");
        return code.ToString();
    }

    private static List<Param> Params(List<object?> items) => items.Select(Obj).Select(ToParam).ToList();

    private static Param ToParam(Dictionary<string, object?> o) => new()
    {
        Name = Str(o, "name") ?? "",
        Type = Str(o, "type") ?? throw new FormatException("ABI parameter without type"),
        InternalType = Str(o, "internalType"),
        Components = Params(Arr(o, "components")),
        Indexed = Bool(o, "indexed"),
    };

    private static string Canonical(Param p)
    {
        if (!p.Type.StartsWith("tuple", StringComparison.Ordinal)) return p.Type;
        return "(" + string.Join(",", p.Components.Select(Canonical)) + ")" + p.Type.Substring(5);
    }

    private static bool IsDynamicOrComposite(Param p) =>
        p.Type is "string" or "bytes" || p.Type.EndsWith("]", StringComparison.Ordinal) || p.Type.StartsWith("tuple", StringComparison.Ordinal);

    // Splits "uint256[2][]" into element "uint256[2]" and the outer suffix "[]".
    private static bool IsArray(string type, out string element)
    {
        element = type;
        if (!type.EndsWith("]", StringComparison.Ordinal)) return false;
        element = type.Substring(0, type.LastIndexOf('['));
        return true;
    }

    private static Param Element(Param p, string elementType) => new() { Name = p.Name, Type = elementType, InternalType = p.InternalType, Components = p.Components };

    [ThreadStatic] private static string? _contractName;

    private static string StructName(Param p, Dictionary<string, Struct> structs, string fallback)
    {
        string name = fallback;
        if (p.InternalType is { } it && it.StartsWith("struct ", StringComparison.Ordinal))
        {
            string t = it.Substring(7);
            int bracket = t.IndexOf('[');
            if (bracket >= 0) t = t.Substring(0, bracket);
            name = t.Substring(t.LastIndexOf('.') + 1);
        }
        name = Names.Pascal(name, fallback);
        if (name == _contractName) name += "Data"; // a nested type cannot share the enclosing class name
        if (!structs.ContainsKey(name)) structs[name] = new Struct { Name = name, Fields = p.Components };
        return name;
    }

    private static string CsType(Param p, Dictionary<string, Struct> structs, string fallback)
    {
        if (IsArray(p.Type, out string element)) return CsType(Element(p, element), structs, fallback) + "[]";
        string t = p.Type;
        if (t == "tuple") return StructName(p, structs, fallback);
        if (t.StartsWith("uint", StringComparison.Ordinal) || t.StartsWith("int", StringComparison.Ordinal)) return "BigInteger";
        return t switch
        {
            "address" => "string",
            "bool" => "bool",
            "string" => "string",
            _ when t.StartsWith("bytes", StringComparison.Ordinal) => "byte[]",
            "function" => "byte[]",
            _ => throw new FormatException($"Unsupported ABI type '{t}'"),
        };
    }

    private static string FromAbi(Param p, string expr, Dictionary<string, Struct> structs, string fallback, int depth)
    {
        if (IsArray(p.Type, out string element))
        {
            string x = "x" + depth;
            var inner = Element(p, element);
            return $"ToArray<{CsType(inner, structs, fallback)}>({expr}, {x} => {FromAbi(inner, x, structs, fallback, depth + 1)})";
        }
        if (p.Type == "tuple") return $"{StructName(p, structs, fallback)}.FromAbi({expr})";
        return $"({CsType(p, structs, fallback)}){expr}!";
    }

    private static string ToAbi(Param p, string expr, Dictionary<string, Struct> structs, int depth)
    {
        if (IsArray(p.Type, out string element))
        {
            var inner = Element(p, element);
            if (!ContainsTuple(inner)) return expr;
            string x = "x" + depth;
            return $"System.Linq.Enumerable.ToArray(System.Linq.Enumerable.Select({expr}, {x} => (object?){ToAbi(inner, x, structs, depth + 1)}))";
        }
        return p.Type == "tuple" ? $"{expr}.ToAbi()" : expr;
    }

    private static bool ContainsTuple(Param p) => p.Type.StartsWith("tuple", StringComparison.Ordinal);

    private sealed class Argument
    {
        public string Name = "";
        public string Type = "";
        public string ToAbi = "";
    }

    private static List<Argument> Arguments(List<Param> inputs, Dictionary<string, Struct> structs, string method)
    {
        var used = new HashSet<string>(StringComparer.Ordinal) { "signer", "block", "ct", "valueWei" };
        var list = new List<Argument>();
        for (int i = 0; i < inputs.Count; i++)
        {
            string name = Names.Camel(inputs[i].Name, "arg" + i);
            while (!used.Add(name)) name += "_";
            list.Add(new Argument { Name = name, Type = CsType(inputs[i], structs, method + "Arg" + i), ToAbi = ToAbi(inputs[i], name, structs, 0) });
        }
        return list;
    }
}
